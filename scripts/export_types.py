"""Generate frontend/src/api/types.ts from the Pydantic contracts.

Usage: python scripts/export_types.py [--out PATH]
CI regenerates to a temp file and diffs against the committed one (PLAN T2).
"""

from __future__ import annotations

import argparse
import inspect
import json
from pathlib import Path
import sys
from typing import Any, Literal

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pydantic import BaseModel  # noqa: E402

from backend.api import schemas  # noqa: E402
from backend.core import models  # noqa: E402

DEFAULT_OUT = ROOT / "frontend" / "src" / "api" / "types.ts"
# Models that are request bodies keep schema defaults optional (validation mode).
REQUEST_MODELS = {"FieldEditRequest"}

HEADER = """\
// GENERATED by scripts/export_types.py from backend/core/models.py and
// backend/api/schemas.py. Do not edit by hand; run `python scripts/export_types.py`.

/** Normalized [y_min, x_min, y_max, x_max], origin top-left, 0.0-1.0. */
export type Box = [number, number, number, number];
"""


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _paren(t: str) -> str:
    return f"({t})" if " | " in t else t


def ts_type(s: dict[str, Any]) -> str:
    """Convert one JSON-schema node to a TypeScript type expression."""
    if "$ref" in s:
        return _ref_name(s["$ref"])
    if "allOf" in s and len(s["allOf"]) == 1:
        return ts_type(s["allOf"][0])
    if "anyOf" in s:
        return " | ".join(ts_type(p) for p in s["anyOf"])
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        prefix = s.get("prefixItems")
        if prefix is not None:
            if len(prefix) == 4 and all(p.get("type") == "number" for p in prefix):
                return "Box"
            return "[" + ", ".join(ts_type(p) for p in prefix) + "]"
        return f"{_paren(ts_type(s.get('items', {})))}[]"
    if t == "object":
        if "properties" in s:
            return _inline_object(s)
        value = (
            ts_type(s["additionalProperties"])
            if isinstance(s.get("additionalProperties"), dict)
            else "unknown"
        )
        if "x-key-type" in s:
            return f"Partial<Record<{s['x-key-type']}, {value}>>"
        if "propertyNames" in s:
            return f"Partial<Record<{ts_type(s['propertyNames'])}, {value}>>"
        return f"Record<string, {value}>"
    return "unknown"


def _inline_object(s: dict[str, Any]) -> str:
    required = set(s.get("required", []))
    parts = [
        f"{name}{'' if name in required else '?'}: {ts_type(p)}"
        for name, p in s["properties"].items()
    ]
    return "{ " + "; ".join(parts) + " }"


def render_def(name: str, s: dict[str, Any]) -> str:
    """Render a named definition as an interface or a union type alias."""
    doc = f"/** {' '.join(s['description'].split())} */\n" if s.get("description") else ""
    if "properties" in s:
        required = set(s.get("required", []))
        lines = [
            f"  {prop}{'' if prop in required else '?'}: {ts_type(p)};"
            for prop, p in s["properties"].items()
        ]
        return f"{doc}export interface {name} {{\n" + "\n".join(lines) + "\n}\n"
    return f"{doc}export type {name} = {ts_type(s)};\n"


def _root_models() -> list[type[BaseModel]]:
    found: dict[str, type[BaseModel]] = {}
    for module in (models, schemas):
        for name, obj in inspect.getmembers(module, inspect.isclass):
            if (
                issubclass(obj, BaseModel)
                and obj is not models.Strict
                and obj.__module__ == module.__name__
            ):
                found[name] = obj
    return [found[n] for n in sorted(found)]


def build_registry() -> dict[str, dict[str, Any]]:
    """Collect every named schema: roots first, then nested $defs (first wins)."""
    registry: dict[str, dict[str, Any]] = {}
    nested: list[dict[str, Any]] = []
    for cls in _root_models():
        mode: Literal["validation", "serialization"] = (
            "validation" if cls.__name__ in REQUEST_MODELS else "serialization"
        )
        schema = cls.model_json_schema(mode=mode)
        nested.append(schema.pop("$defs", {}))
        schema.pop("title", None)
        registry[cls.__name__] = schema
    for defs in nested:
        for name, s in defs.items():
            registry.setdefault(name, {k: v for k, v in s.items() if k != "title"})
    return registry


def render() -> str:
    registry = build_registry()
    chunks = [HEADER]
    for name in sorted(registry):
        chunks.append(render_def(name, registry[name]))
    union = " | ".join(t.__name__ for t in schemas.SSE_EVENT_TYPES)
    chunks.append(f"export type SseEvent = {union};\n")
    return "\n".join(chunks)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
